import { readFile } from "node:fs/promises";
import { evaluateLegalPredeploymentReadiness } from "../lib/legal-predeployment-readiness.mjs";

const argument = (name) => { const index = process.argv.indexOf(name); return index < 0 ? null : process.argv[index + 1] ?? null; };
const json = async (name) => { const value = argument(name); if (value === null) return null; if (!value) throw new Error("R6_LEGAL_PREDEPLOYMENT_EVIDENCE_INPUT_REQUIRED"); return JSON.parse(await readFile(value, "utf8")); };
const targetBinding = await json("--target-binding");
const baselineManifest = await json("--baseline-manifest");
const baselineTerminal = await json("--baseline-terminal");
const baselineCheckpoint = await json("--baseline-checkpoint");
const baselineJournal = await json("--baseline-journal");
const rebuildRestoreEvidence = await json("--rebuild-evidence");
const migrationJournal = await json("--migration-journal");
const migrationTerminal = await json("--migration-terminal");
const smokeTerminal = await json("--smoke-terminal");
const cleanupTerminal = await json("--cleanup-terminal");
const runtimeManifest = await json("--runtime-manifest");
const runtimeCapability = await json("--runtime-capability");
const rebuiltRuntimeCapability = await json("--rebuilt-runtime-capability");
const orchestratorTerminal = await json("--orchestrator-terminal");
const taskConsumption = await json("--task-consumption");
const implementationCommit = argument("--implementation-commit");
process.stdout.write(`${JSON.stringify(evaluateLegalPredeploymentReadiness({ targetBinding, baselineManifest, baselineTerminal, baselineCheckpoint, baselineJournal, rebuildRestoreEvidence, migrationJournal, migrationTerminal, smokeTerminal, cleanupTerminal, runtimeManifest, runtimeCapability, rebuiltRuntimeCapability, orchestratorTerminal, taskConsumption, implementationCommit }))}\n`);
