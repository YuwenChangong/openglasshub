import assert from "node:assert/strict";
import { getBearerToken } from "../src/lib/server/admin-auth.ts";
import { LEGAL_POLICY } from "../src/lib/legal-policy.ts";
import { handleLegalConsentPost } from "../src/lib/server/legal-consent-api.server.ts";

const actorId = "00000000-0000-0000-0000-000000000201";
const otherActorId = "00000000-0000-0000-0000-000000000202";

function request(body, authorization = "Bearer verified-token") {
  const headers = { "content-type": "application/json" };
  if (authorization !== null) headers.authorization = authorization;
  return new Request("https://unit.test/api/legal/consent", {
    method: "POST",
    headers,
    body: JSON.stringify(body),
  });
}

async function responseJson(response) {
  return { status: response.status, body: await response.json() };
}

function activeRecord(overrides = {}) {
  return {
    userId: actorId,
    bundleVersion: LEGAL_POLICY.bundleVersion,
    termsVersion: LEGAL_POLICY.termsVersion,
    privacyVersion: LEGAL_POLICY.privacyVersion,
    guidelinesVersion: LEGAL_POLICY.guidelinesVersion,
    minimumAge: LEGAL_POLICY.minimumAge,
    lastConfirmedAt: "2026-07-14T00:00:00.000Z",
    ...overrides,
  };
}

function dependenciesFor({ record = null, readFailure = false, writeFailure = false, now = "2026-07-14T00:02:00.000Z" } = {}) {
  const events = [];
  const writes = [];
  return {
    events,
    writes,
    dependencies: {
      async authenticate(req) {
        events.push(`authenticate:${req.headers.get("authorization") ?? "missing"}`);
        if (req.headers.get("authorization") !== "Bearer verified-token") return null;
        return {
          userId: actorId,
          readRepository: {
            async findByUserAndBundle(userId, bundleVersion) {
              events.push(`read:${userId}:${bundleVersion}`);
              assert.equal(userId, actorId, "the read repository receives only the verified actor");
              assert.equal(bundleVersion, LEGAL_POLICY.bundleVersion, "the active bundle is server-selected");
              if (readFailure) throw new Error("database details must stay internal");
              return record;
            },
          },
        };
      },
      createWriteRepository(verifiedUserId) {
        events.push(`writer:${verifiedUserId}`);
        assert.equal(verifiedUserId, actorId, "the writer can only be bound to the verified actor");
        return {
          async recordCurrentAcceptance(params) {
            events.push("write");
            if (writeFailure) throw new Error("service role details must stay internal");
            assert.equal("userId" in params, false, "the repository cannot receive a caller-selected user id");
            assert.equal("acceptedAt" in params, false, "timestamps are generated by the database");
            assert.equal(params.bundleVersion, LEGAL_POLICY.bundleVersion);
            writes.push({ actorId: verifiedUserId, ...params });
          },
        };
      },
      now: () => Date.parse(now),
    },
  };
}

const validPayload = { accepted: true, source: "login" };

assert.equal(getBearerToken(new Request("https://unit.test", { headers: { authorization: "Bearer verified-token" } })), "verified-token");
for (const authorization of [null, "Basic invalid", "Bearer", "Bearer verified-token extra", "Bearer\t"]) {
  assert.equal(getBearerToken(new Request("https://unit.test", { headers: authorization ? { authorization } : {} })), null);
}

for (const authorization of [null, "Basic invalid", "Bearer invalid-token", "Bearer verified-token extra"]) {
  const fixture = dependenciesFor();
  const result = await responseJson(await handleLegalConsentPost(
    request(validPayload, authorization),
    fixture.dependencies,
  ));
  assert.deepEqual(result, { status: 401, body: { error: "UNAUTHORIZED" } });
  assert.equal(fixture.events.some((event) => event.startsWith("writer:")), false);
  assert.equal(fixture.writes.length, 0);
}

for (const payload of [
  { source: "login" },
  { accepted: false, source: "login" },
  { accepted: true, source: "invalid" },
  { accepted: true, source: "login", user_id: otherActorId },
  { accepted: true, source: "login", bundleVersion: "stale" },
  { accepted: true, source: "login", acceptedAt: "2026-01-01T00:00:00.000Z" },
  { accepted: true, source: "login", analytics: false },
  { accepted: true, source: "login", marketing: false },
]) {
  const fixture = dependenciesFor();
  const result = await responseJson(await handleLegalConsentPost(request(payload), fixture.dependencies));
  assert.equal(result.status, 400);
  assert.equal(fixture.events.some((event) => event.startsWith("writer:")), false);
  assert.equal(fixture.writes.length, 0);
}

{
  const fixture = dependenciesFor();
  const result = await responseJson(await handleLegalConsentPost(request(validPayload), fixture.dependencies));
  assert.deepEqual(result, {
    status: 200,
    body: { current: true, bundleVersion: LEGAL_POLICY.bundleVersion, minimumAge: LEGAL_POLICY.minimumAge, consentUrl: "/legal-consent/" },
  });
  assert.deepEqual(fixture.events, [
    "authenticate:Bearer verified-token",
    `read:${actorId}:${LEGAL_POLICY.bundleVersion}`,
    `writer:${actorId}`,
    "write",
  ]);
  assert.deepEqual(fixture.writes, [{
    actorId,
    bundleVersion: LEGAL_POLICY.bundleVersion,
    termsVersion: LEGAL_POLICY.termsVersion,
    privacyVersion: LEGAL_POLICY.privacyVersion,
    guidelinesVersion: LEGAL_POLICY.guidelinesVersion,
    minimumAge: LEGAL_POLICY.minimumAge,
    consentUrl: "/legal-consent/",
    source: "login",
  }]);
}

{
  const fixture = dependenciesFor({ record: activeRecord({ termsVersion: "2026-06" }) });
  const result = await responseJson(await handleLegalConsentPost(request(validPayload), fixture.dependencies));
  assert.equal(result.status, 200, "outdated required consent renews using the active server bundle");
  assert.equal(fixture.writes[0]?.bundleVersion, LEGAL_POLICY.bundleVersion);
}

{
  const fixture = dependenciesFor();
  const first = await responseJson(await handleLegalConsentPost(request(validPayload), fixture.dependencies));
  const second = await responseJson(await handleLegalConsentPost(request(validPayload), fixture.dependencies));
  assert.equal(first.status, 200);
  assert.equal(second.status, 200);
  assert.deepEqual(fixture.writes[0], fixture.writes[1], "retries submit the same actor-bound active bundle for the RPC upsert boundary");
}

{
  const fixture = dependenciesFor({
    record: activeRecord({ lastConfirmedAt: "2026-07-14T00:00:00.000Z" }),
    now: "2026-07-14T00:00:30.000Z",
  });
  const result = await responseJson(await handleLegalConsentPost(request(validPayload), fixture.dependencies));
  assert.deepEqual(result, { status: 429, body: { error: "LEGAL_CONSENT_RATE_LIMITED" } });
  assert.equal(fixture.events.some((event) => event.startsWith("writer:")), false);
}

for (const options of [{ readFailure: true }, { writeFailure: true }]) {
  const fixture = dependenciesFor(options);
  const result = await responseJson(await handleLegalConsentPost(request(validPayload), fixture.dependencies));
  assert.deepEqual(result, { status: 500, body: { error: "LEGAL_CONSENT_UNAVAILABLE" } });
  assert.equal("message" in result.body, false);
}

