async function walk(dir) {
  const items = await fs.readdir(dir, { withFileTypes: true });
  return (await Promise.all(items.map((item) => (item.isDirectory() ? walk(path.join(dir, item.name)) : [path.join(dir, item.name)])))).flat();
}

