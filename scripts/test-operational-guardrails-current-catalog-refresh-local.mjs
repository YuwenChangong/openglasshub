import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { parseCsv, validateCurrentCatalogRefreshRows } from "./operational-guardrails-current-catalog-refresh-core.mjs";

const packet = await readFile("docs/ops/reconciliation/operational-guardrails-current-catalog-refresh.sql", "utf8");
const containerNames = execFileSync("docker", ["ps", "--format", "{{.Names}}"], { encoding: "utf8" }).split(/\r?\n/).filter((name) => name.startsWith("supabase_db_local-supabase-normalized-replay-"));
assert.equal(containerNames.length, 1, "LOCAL_DOCKER_ONLY requires exactly one normalized replay PostgreSQL container");
assert.match(packet, /^BEGIN TRANSACTION READ ONLY;/m);
assert.match(packet, /\nROLLBACK;\s*$/);
assert.doesNotMatch(packet, /from\s+public\.forum_upload_attempts\b/i, "packet must not read application rows");
assert.doesNotMatch(packet, /auth\.users/i, "packet must not inspect auth-user rows");

const container = containerNames[0];
const database = "openglass_current_catalog_refresh_sim";
const psql = (input, databaseName = database, csv = false) => spawnSync("docker", ["exec", "-i", container, "psql", "-X", "-q", ...(csv ? ["--csv"] : ["-At"]), "-v", "ON_ERROR_STOP=1", "-U", "postgres", "-d", databaseName], { input, encoding: "utf8" });
const mustRun = (input, databaseName, csv) => {
  const result = psql(input, databaseName, csv);
  if (result.status !== 0) throw new Error(result.stderr || result.stdout || "local PostgreSQL command failed");
  return result.stdout;
};
const roles = ["anon", "authenticated", "service_role", "authenticator"];
let createdRoles = [];

try {
  for (const role of roles) {
    const exists = mustRun(`SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${role}');`, "postgres").trim() === "t";
    if (!exists) {
      mustRun(`CREATE ROLE ${role} NOLOGIN;`, "postgres");
      createdRoles.push(role);
    }
  }
  mustRun(`DROP DATABASE IF EXISTS ${database}; CREATE DATABASE ${database};`, "postgres");
  mustRun(`
    CREATE SCHEMA auth;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS 'SELECT NULL::uuid';
    CREATE TABLE public.forum_upload_attempts (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id uuid,
      purpose text NOT NULL,
      ip_hash text NOT NULL,
      bytes bigint NOT NULL DEFAULT 0,
      created_at timestamptz NOT NULL DEFAULT now()
    );
    ALTER TABLE public.forum_upload_attempts ENABLE ROW LEVEL SECURITY;
    CREATE POLICY forum_upload_attempts_insert_authenticated ON public.forum_upload_attempts FOR INSERT TO authenticated WITH CHECK ((user_id = auth.uid()) OR (user_id IS NULL));
    CREATE POLICY forum_upload_attempts_insert_self ON public.forum_upload_attempts FOR INSERT TO authenticated WITH CHECK ((purpose = 'post_create') AND (user_id = auth.uid()));
    CREATE POLICY forum_upload_attempts_select_authenticated ON public.forum_upload_attempts FOR SELECT TO authenticated USING (true);
    CREATE POLICY forum_upload_attempts_select_self ON public.forum_upload_attempts FOR SELECT TO authenticated USING ((user_id = auth.uid()) OR (user_id IS NULL));
    CREATE INDEX forum_upload_attempts_purpose_ip_created_idx ON public.forum_upload_attempts USING btree (purpose, ip_hash, created_at DESC);
    CREATE INDEX forum_upload_attempts_purpose_user_created_idx ON public.forum_upload_attempts USING btree (purpose, user_id, created_at DESC);
    REVOKE ALL ON public.forum_upload_attempts FROM PUBLIC, anon, authenticated, service_role;
  `);
  const csv = mustRun(packet, database, true);
  const validation = validateCurrentCatalogRefreshRows(parseCsv(csv));
  assert.equal(validation.sectionCount, 20);
  assert.equal(validation.indexFindings.forum_upload_attempts_purpose_ip_created_idx, "EXACT_INDEX_PRESENT");
  assert.equal(validation.indexFindings.forum_upload_attempts_purpose_user_created_idx, "EXACT_INDEX_PRESENT");
  assert.equal(validation.effectiveTablePrivileges.authenticated.SELECT, false);
  assert.equal(validation.effectiveTablePrivileges.authenticated.INSERT, false);
  assert.equal(validation.policyFindings.forum_upload_attempts_insert_self, "RLS_REDUNDANT_PRIVILEGE_HOLD");
  assert.equal(validation.policyRemovalEligible, false);
} finally {
  try { mustRun(`DROP DATABASE IF EXISTS ${database};`, "postgres"); } catch (error) { console.error(error); process.exitCode = 1; }
  for (const role of createdRoles.reverse()) {
    try { mustRun(`DROP ROLE IF EXISTS ${role};`, "postgres"); } catch (error) { console.error(error); process.exitCode = 1; }
  }
}

console.log(JSON.stringify({ localDockerOnly: true, currentCatalogPacketCompleted: true, applicationRowsRead: false, explicitRollbackReached: true, productionOperations: 0 }));
